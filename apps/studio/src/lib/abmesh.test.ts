import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import {
  ABMESH_FLAGS,
  ABMESH_MAGIC,
  coordToWorld,
  inspectVoxel,
  parseAbMesh01,
  readMctsTriples,
  readPolicyPairs,
} from "./abmesh";

function fixtureBuffer(): ArrayBuffer {
  const here = dirname(fileURLToPath(import.meta.url));
  const bytes = readFileSync(resolve(here, "__fixtures__/abmesh_fixture.bin"));
  return bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer;
}

describe("parseAbMesh01", () => {
  it("parses the fixture generated by ab-core (Rust)", () => {
    const frame = parseAbMesh01(fixtureBuffer());
    expect(frame.dims).toEqual([2, 2, 2]);
    expect(frame.stepIndex).toBe(3);
    expect(frame.positions.length).toBe(96 * 3);
    expect(frame.indices.length).toBe(144);
    expect(frame.voxelIds.length).toBe(96);
    expect(frame.metadata.step).toBe(3);
    expect(frame.metadata.phase).toBe("REFINEMENT");
    expect(frame.metadata.mcts_stats?.refutation).toBe(true);
    expect(frame.metadata.reward_v33.total_reward).toBeCloseTo(0.55, 6);
    expect(frame.flags & ABMESH_FLAGS.POLICY).toBeTruthy();
    expect(frame.flags & ABMESH_FLAGS.BLUEPRINT).toBeTruthy();
    expect(frame.dispP99).toBeCloseTo(41.2, 5);
    expect(frame.strainP99).toBeCloseTo(0.75, 5);
  });

  it("reads policy pairs and MCTS triples without copies", () => {
    const frame = parseAbMesh01(fixtureBuffer());
    expect(readPolicyPairs(frame.policyAddRaw, frame.policyAddCount)).toEqual([
      { flat_idx: 0, prob: 0.5 },
      { flat_idx: 3, prob: 0.25 },
    ]);
    expect(readPolicyPairs(frame.policyRemRaw, frame.policyRemCount)).toEqual([
      { flat_idx: 6, prob: 0.125 },
    ]);
    const triples = readMctsTriples(frame.mctsAddRaw, frame.mctsAddCount);
    expect(triples[0]?.flat_idx).toBe(0);
    expect(triples[0]?.visits).toBe(48);
    expect(triples[0]?.q_value).toBeCloseTo(0.61, 6);
    expect(frame.diffAdded).toEqual(new Uint32Array([1, 3]));
    expect(frame.diffRemoved).toEqual(new Uint32Array([6]));
  });

  it("inspects a voxel by id", () => {
    const frame = parseAbMesh01(fixtureBuffer());
    const voxel = inspectVoxel(frame, 0);
    expect(voxel).not.toBeNull();
    expect(voxel?.x).toBe(0);
    expect(voxel?.y).toBe(0);
    expect(voxel?.z).toBe(0);
    expect(voxel?.density).toBe(1);
    expect(voxel?.policy_add).toBe(0.5);
  });

  it("rejects corrupt buffers", () => {
    const buffer = fixtureBuffer();
    expect(() => parseAbMesh01(buffer.slice(0, 40))).toThrow(/header/);
    const copy = buffer.slice(0);
    new Uint8Array(copy)[0] = 0x58;
    expect(() => parseAbMesh01(copy)).toThrow(/magic/);
    const truncated = buffer.slice(0, buffer.byteLength - 1);
    expect(() => parseAbMesh01(truncated)).toThrow(/divergente|cursor/);
  });

  it("keeps the world-space convention", () => {
    expect(coordToWorld(0, 0, 0, [64, 32, 8])).toEqual([-31.5, 0.5, -3.5]);
    expect(coordToWorld(63, 16, 4, [64, 32, 8])).toEqual([31.5, 16.5, 0.5]);
  });

  it("exports the normative magic", () => {
    expect(ABMESH_MAGIC).toBe("ABMESH01");
  });
});
